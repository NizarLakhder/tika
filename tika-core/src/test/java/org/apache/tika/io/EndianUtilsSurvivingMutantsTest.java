package org.apache.tika.io;

import static org.junit.jupiter.api.Assertions.assertEquals;
import static org.junit.jupiter.api.Assertions.assertThrows;

import java.io.ByteArrayInputStream;
import java.io.IOException;
import java.io.InputStream;

import org.junit.jupiter.api.Test;

/**
 * Hand-written tests for the {@link EndianUtils} mutants that survive both the original
 * {@link EndianUtilsTest} and the tests generated by ChatUniTest.
 * <p>
 * The survivors are in the end-of-stream guard of the {@code read*} methods,
 * {@code if ((ch1 | ch2 | ...) < 0)}, and in the loop bounds of
 * {@link EndianUtils#readUE7(InputStream)}. One last test covers a line that had no mutant
 * and no test at all.
 */
public class EndianUtilsSurvivingMutantsTest {

    /**
     * A stream whose {@link InputStream#read()} returns the given values in order, then -1.
     * Unlike a {@link ByteArrayInputStream} it can report end of stream and still return
     * data afterwards, as a stream over a file that is being appended to would.
     */
    private static InputStream scripted(final int... values) {
        return new InputStream() {
            private int next = 0;

            @Override
            public int read() {
                return next < values.length ? values[next++] : -1;
            }
        };
    }

    /**
     * Zero is a valid 16-bit value, not an end of stream.
     */
    @Test
    public void testReadUShortOfZeroBytesIsZero() throws Exception {
        assertEquals(0, EndianUtils.readUShortLE(new ByteArrayInputStream(new byte[2])));
        assertEquals(0, EndianUtils.readUShortBE(new ByteArrayInputStream(new byte[2])));
    }

    /**
     * Zero is a valid unsigned 32-bit value, not an end of stream.
     */
    @Test
    public void testReadUIntOfZeroBytesIsZero() throws Exception {
        assertEquals(0L, EndianUtils.readUIntLE(new ByteArrayInputStream(new byte[4])));
        assertEquals(0L, EndianUtils.readUIntBE(new ByteArrayInputStream(new byte[4])));
    }

    /**
     * Zero is a valid signed 32-bit value in every byte order, not an end of stream.
     */
    @Test
    public void testReadIntOfZeroBytesIsZero() throws Exception {
        assertEquals(0, EndianUtils.readIntLE(new ByteArrayInputStream(new byte[4])));
        assertEquals(0, EndianUtils.readIntBE(new ByteArrayInputStream(new byte[4])));
        assertEquals(0, EndianUtils.readIntME(new ByteArrayInputStream(new byte[4])));
    }

    /**
     * Zero is a valid 64-bit value, not an end of stream.
     */
    @Test
    public void testReadLongOfZeroBytesIsZero() throws Exception {
        assertEquals(0L, EndianUtils.readLongLE(new ByteArrayInputStream(new byte[8])));
        assertEquals(0L, EndianUtils.readLongBE(new ByteArrayInputStream(new byte[8])));
    }

    /**
     * A stream one byte too short is an underrun for every fixed-width read.
     */
    @Test
    public void testTruncatedStreamIsRejected() {
        byte[] one = {0x01};
        byte[] three = {0x01, 0x02, 0x03};
        byte[] seven = {0x01, 0x02, 0x03, 0x04, 0x05, 0x06, 0x07};

        assertThrows(EndianUtils.BufferUnderrunException.class,
                () -> EndianUtils.readUShortLE(new ByteArrayInputStream(one)));
        assertThrows(EndianUtils.BufferUnderrunException.class,
                () -> EndianUtils.readUShortBE(new ByteArrayInputStream(one)));
        assertThrows(EndianUtils.BufferUnderrunException.class,
                () -> EndianUtils.readUIntLE(new ByteArrayInputStream(three)));
        assertThrows(EndianUtils.BufferUnderrunException.class,
                () -> EndianUtils.readUIntBE(new ByteArrayInputStream(three)));
        assertThrows(EndianUtils.BufferUnderrunException.class,
                () -> EndianUtils.readIntLE(new ByteArrayInputStream(three)));
        assertThrows(EndianUtils.BufferUnderrunException.class,
                () -> EndianUtils.readIntBE(new ByteArrayInputStream(three)));
        assertThrows(EndianUtils.BufferUnderrunException.class,
                () -> EndianUtils.readIntME(new ByteArrayInputStream(three)));
        assertThrows(EndianUtils.BufferUnderrunException.class,
                () -> EndianUtils.readLongLE(new ByteArrayInputStream(seven)));
        assertThrows(EndianUtils.BufferUnderrunException.class,
                () -> EndianUtils.readLongBE(new ByteArrayInputStream(seven)));
    }

    /**
     * An end of stream reported by the first read only is still an underrun: every read
     * result takes part in the check, not just the last one.
     */
    @Test
    public void testReadUIntDetectsEndOfStreamOnFirstRead() {
        assertThrows(EndianUtils.BufferUnderrunException.class,
                () -> EndianUtils.readUIntLE(scripted(-1, 0x01, 0x02, 0x03)));
        assertThrows(EndianUtils.BufferUnderrunException.class,
                () -> EndianUtils.readUIntBE(scripted(-1, 0x01, 0x02, 0x03)));
    }

    /**
     * Same as {@link #testReadUIntDetectsEndOfStreamOnFirstRead()} for the signed reads.
     */
    @Test
    public void testReadIntDetectsEndOfStreamOnFirstRead() {
        assertThrows(EndianUtils.BufferUnderrunException.class,
                () -> EndianUtils.readIntLE(scripted(-1, 0x01, 0x02, 0x03)));
        assertThrows(EndianUtils.BufferUnderrunException.class,
                () -> EndianUtils.readIntBE(scripted(-1, 0x01, 0x02, 0x03)));
        assertThrows(EndianUtils.BufferUnderrunException.class,
                () -> EndianUtils.readIntME(scripted(-1, 0x01, 0x02, 0x03)));
    }

    /**
     * Same as {@link #testReadUIntDetectsEndOfStreamOnFirstRead()} for the 64-bit reads.
     */
    @Test
    public void testReadLongDetectsEndOfStreamOnFirstRead() {
        assertThrows(EndianUtils.BufferUnderrunException.class,
                () -> EndianUtils.readLongLE(scripted(-1, 0x01, 0x02, 0x03, 0x04, 0x05, 0x06, 0x07)));
        assertThrows(EndianUtils.BufferUnderrunException.class,
                () -> EndianUtils.readLongBE(scripted(-1, 0x01, 0x02, 0x03, 0x04, 0x05, 0x06, 0x07)));
    }

    /**
     * A zero byte that ends a UE7 number is data: it still shifts the value by seven bits.
     */
    @Test
    public void testReadUE7ZeroByteAfterContinuation() throws Exception {
        byte[] data = {(byte) 0x81, 0x00};
        assertEquals(128L, EndianUtils.readUE7(new ByteArrayInputStream(data)));
    }

    /**
     * At most six bytes are decoded: a seventh byte does not contribute to the value.
     */
    @Test
    public void testReadUE7StopsAfterSixBytes() throws Exception {
        byte[] data = {(byte) 0x81, (byte) 0x80, (byte) 0x80, (byte) 0x80, (byte) 0x80, (byte) 0x80, 0x01};
        assertEquals(1L << 35, EndianUtils.readUE7(new ByteArrayInputStream(data)));
    }

    /**
     * A UE7 number cut off after a continuation byte is an error, not a shorter value.
     * No mutant survives here: the {@code throw} this test reaches was simply never executed.
     */
    @Test
    public void testReadUE7TruncatedNumberIsRejected() {
        byte[] data = {(byte) 0x81};
        assertThrows(IOException.class, () -> EndianUtils.readUE7(new ByteArrayInputStream(data)));
    }
}
